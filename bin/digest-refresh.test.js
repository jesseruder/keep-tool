'use strict';

const assert = require('node:assert/strict');
const test = require('node:test');
const { createDigestRefresh } = require('./digest-refresh.js');

test('digest refresh coalesces slow work, returns the cached value, and holds restart admission', async () => {
  let resolveRun;
  let calls = 0;
  let active = 0;
  const rows = [];
  let changes = 0;
  const refresh = createDigestRefresh({
    root: '/registry',
    now: () => new Date(2026, 8, 25, 8, 0),
    health: { record: (name, value) => rows.push([name, value]) },
    restartGate: { enter: () => { active++; return () => { active--; }; } },
    mutationProcess: { run: async (operation, input) => {
      calls++;
      assert.equal(operation, 'ensure-digest');
      assert.deepEqual(input, { root: '/registry', today: '2026-09-25', createAllowed: true });
      return new Promise((resolve) => { resolveRun = resolve; });
    } },
    onChange: () => { changes++; },
  });
  assert.equal(refresh.snapshot(), null, 'dashboard preparation does not wait for digest work');
  assert.equal(refresh.snapshot(), null);
  await Promise.resolve();
  assert.equal(calls, 1);
  assert.equal(active, 1);
  resolveRun({ date: '2026-09-25', md: '# digest\n', detail: 'generated' });
  while (refresh.running) await new Promise((resolve) => setImmediate(resolve));
  assert.deepEqual(refresh.snapshot(), { date: '2026-09-25', md: '# digest\n' });
  assert.equal(active, 0);
  assert.equal(changes, 1);
  assert.deepEqual(rows, [['digest', { ok: true, detail: 'generated' }]]);
});

test('digest refresh releases restart admission and records child errors', async () => {
  let active = 0;
  const rows = [];
  const lines = [];
  const refresh = createDigestRefresh({
    root: '/registry', now: () => new Date(2026, 8, 25, 9, 0),
    health: { record: (name, value) => rows.push([name, value]) },
    restartGate: { enter: () => { active++; return () => { active--; }; } },
    mutationProcess: { run: async () => { throw new Error('child failed'); } },
    write: (line) => lines.push(line),
  });
  assert.equal(await refresh.refresh(), null);
  assert.equal(active, 0);
  assert.equal(rows[0][0], 'digest');
  assert.equal(rows[0][1].ok, false);
  assert.equal(rows[0][1].error.message, 'child failed');
  assert.deepEqual(lines, ['keep serve: digest failed: child failed\n']);
});

test('digest refresh does not stamp a day before 05:00', async () => {
  let calls = 0;
  let clock = new Date(2026, 8, 25, 4, 58, 0);
  const rows = [];
  const refresh = createDigestRefresh({
    root: '/registry', now: () => clock,
    health: { record: (name, value) => rows.push([name, value]) },
    mutationProcess: { run: async (operation, input) => {
      calls++;
      assert.equal(input.createAllowed, false);
      return { date: input.today, md: calls === 1 ? null : '# made by CLI\n', detail: calls === 1 ? 'nothing due' : 'exists' };
    } },
  });
  assert.equal(await refresh.refresh(), null);
  assert.equal(refresh.snapshot(), null);
  assert.equal(calls, 1, 'the child still checks for a digest generated by a CLI');
  assert.deepEqual(rows, [['digest', { ok: true, skipped: true, detail: 'nothing due' }]]);
  clock = new Date(2026, 8, 25, 4, 59, 1);
  assert.equal(refresh.snapshot(), null);
  while (refresh.running) await new Promise((resolve) => setImmediate(resolve));
  assert.deepEqual(refresh.snapshot(), { date: '2026-09-25', md: '# made by CLI\n' },
    'a digest generated externally in the small hours appears after the bounded retry');
});

test('a restart-gate refusal clears the singleton so a later refresh can retry', async () => {
  let attempts = 0;
  let runs = 0;
  const refresh = createDigestRefresh({
    root: '/registry', now: () => new Date(2026, 8, 25, 9, 0),
    health: { record: () => {} }, write: () => {},
    restartGate: { enter: () => {
      attempts++;
      if (attempts === 1) throw new Error('restart pending');
      return () => {};
    } },
    mutationProcess: { run: async () => {
      runs++;
      return { date: '2026-09-25', md: '# ready\n', detail: 'exists' };
    } },
  });
  assert.equal(await refresh.refresh(), null);
  assert.equal(refresh.running, false);
  assert.deepEqual(await refresh.refresh(), { date: '2026-09-25', md: '# ready\n' });
  assert.equal(runs, 1);
});
