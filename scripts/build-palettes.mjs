import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEFAULT_PALETTE, PALETTES } from '../web/app/palettes.js';

const HEADER = '/* generated by scripts/build-palettes.mjs from web/app/palettes.js — do not edit */';

function block(selector, mode, tokens) {
  const declarations = [
    `  color-scheme: ${mode};`,
    ...Object.entries(tokens).map(([name, value]) => `  ${name}: ${value};`),
  ].join('\n');
  return `${selector} {\n${declarations}\n}`;
}

function mediaBlock(selector, tokens) {
  return `@media (prefers-color-scheme: light) {\n${block(selector, 'light', tokens).split('\n').map((line) => `  ${line}`).join('\n')}\n}`;
}

export function render() {
  const output = [HEADER];
  const defaultPalette = PALETTES.find((palette) => palette.id === DEFAULT_PALETTE);
  output.push(block(':root', 'dark', defaultPalette.dark));
  output.push(mediaBlock(':root:not([data-theme="dark"])', defaultPalette.light));
  output.push(block(':root[data-theme="light"]', 'light', defaultPalette.light));

  for (const palette of PALETTES) {
    const selector = `:root[data-palette="${palette.id}"]`;
    output.push(block(selector, 'dark', palette.dark));
    output.push(mediaBlock(`:root:not([data-theme="dark"])[data-palette="${palette.id}"]`, palette.light));
    output.push(block(`:root[data-theme="light"][data-palette="${palette.id}"]`, 'light', palette.light));
  }
  return `${output.join('\n\n')}\n`;
}

const scriptPath = fileURLToPath(import.meta.url);
if (process.argv[1] && path.resolve(process.argv[1]) === scriptPath) {
  const outputPath = path.resolve(path.dirname(scriptPath), '../web/app/palettes.css');
  fs.writeFileSync(outputPath, render());
}
